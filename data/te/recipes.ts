export const recipes = recipeCatalog.filter(
  (recipe) => !redirectedRecipeSlugs.has(recipe.slug),
);

// === HELPER FUNCTIONS ===

export function getRecipeBySlug(slug: string): Recipe | undefined {
  return recipes.find(r => r.slug === slug);
}

export function getRecipesByMillet(milletSlug: string): Recipe[] {
  return recipes.filter(r => r.millets.includes(milletSlug));
}

export function getRecipesByCategory(category: RecipeCategory): Recipe[] {
  return recipes.filter(r => r.category === category);
}
